#!/usr/bin/env python3
"""
generate_report.py — Generate MD and PDF reports from a benchmark results JSON.

Usage:
  python scripts/generate_report.py results/20260925_101200.json
  python scripts/generate_report.py results/20260925_101200.json --out-dir reports/
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


# ── Markdown ──────────────────────────────────────────────────────────────────

def render_markdown(payload: dict) -> str:
    ts = payload.get("timestamp", "unknown")
    results = payload["results"]

    # Group by task
    by_task: dict[str, list[dict]] = defaultdict(list)
    for r in results:
        by_task[r["task"]].append(r)

    # Gather unique models in appearance order
    seen_models: dict[str, str] = {}
    for r in results:
        seen_models[r["model_id"]] = r["model_label"]

    lines = [
        "# LLM Benchmark Report",
        "",
        f"**Generated:** {ts}  ",
        f"**Models:** {', '.join(seen_models.values())}  ",
        f"**Tasks:** {len(by_task)}  ",
        "",
        "---",
        "",
        "## Performance Summary",
        "",
    ]

    # Header row
    model_labels = list(seen_models.values())
    header = "| Task |" + "".join(f" {lbl} latency | {lbl} tok/s |" for lbl in model_labels)
    sep    = "|------|" + "".join(" ---: | ---: |" for _ in model_labels)
    lines += [header, sep]

    for task_id, rs in by_task.items():
        row = f"| {rs[0]['task_label']} |"
        by_model = {r["model_id"]: r for r in rs}
        for mid in seen_models:
            r = by_model.get(mid)
            if r and not r.get("error"):
                v = r["metadata"].get("verdict", "~")
                flag = {"pass": "✓", "fail": "✗", "manual": "~", "error": "✗"}.get(v, "~")
                row += f" {r['latency_s']}s {flag} | {r['tok_per_sec']} |"
            else:
                err = r["error"][:40] if r and r.get("error") else "—"
                row += f" ✗ {err} | — |"
        lines.append(row)

    lines += ["", "---", ""]

    # Per-task detail
    lines.append("## Detailed Responses")
    lines.append("")

    for task_id, rs in by_task.items():
        lines.append(f"### {rs[0]['task_label']}")
        lines.append("")
        lines.append(f"> **Prompt:** {rs[0]['prompt']}")
        lines.append("")

        for r in rs:
            v = r["metadata"].get("verdict", "manual")
            badge = {"pass": "✅ PASS", "fail": "❌ FAIL", "manual": "🔍 Manual review", "error": "💥 Error"}.get(v, "")
            lines.append(f"#### {r['model_label']}  ·  {r['latency_s']}s  ·  {r['tokens_out']} tokens  ·  {badge}")
            lines.append("")
            if r.get("error"):
                lines.append(f"> ⚠️ **Error:** {r['error']}")
            else:
                lines.append(r["response"])
            lines.append("")

        lines += ["---", ""]

    # Aggregate stats
    lines.append("## Aggregate Statistics")
    lines.append("")
    lines.append("| Model | Avg Latency (s) | Avg Tok/s | Tasks Run | Errors |")
    lines.append("|-------|----------------:|----------:|----------:|-------:|")

    for mid, mlabel in seen_models.items():
        model_results = [r for r in results if r["model_id"] == mid and not r.get("error")]
        errors = sum(1 for r in results if r["model_id"] == mid and r.get("error"))
        if model_results:
            avg_lat = round(sum(r["latency_s"] for r in model_results) / len(model_results), 2)
            avg_tps = round(sum(r["tok_per_sec"] for r in model_results) / len(model_results), 1)
            lines.append(f"| {mlabel} | {avg_lat} | {avg_tps} | {len(model_results)} | {errors} |")
        else:
            lines.append(f"| {mlabel} | — | — | 0 | {errors} |")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("*Report generated by [agy-benchmark](https://github.com/agy-benchmark/agy-benchmark) · Sai Kesava Matham · Apache 2.0*")

    return "\n".join(lines)


# ── PDF ───────────────────────────────────────────────────────────────────────

def render_pdf(payload: dict, out_path: str) -> None:
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import inch, cm
        from reportlab.lib.enums import TA_LEFT, TA_CENTER
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
            PageBreak, HRFlowable,
        )
    except ImportError:
        print("reportlab not installed — skipping PDF: pip install reportlab", file=sys.stderr)
        return

    ts = payload.get("timestamp", "unknown")
    results = payload["results"]

    by_task: dict[str, list[dict]] = defaultdict(list)
    for r in results:
        by_task[r["task"]].append(r)

    seen_models: dict[str, str] = {}
    for r in results:
        seen_models[r["model_id"]] = r["model_label"]

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("ReportTitle", parent=styles["Title"],
                                  fontSize=22, spaceAfter=6, textColor=colors.HexColor("#1a1a2e"))
    h1 = ParagraphStyle("H1", parent=styles["Heading1"],
                         fontSize=15, textColor=colors.HexColor("#16213e"), spaceBefore=16, spaceAfter=6)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"],
                         fontSize=12, textColor=colors.HexColor("#0f3460"), spaceBefore=12, spaceAfter=4)
    body = ParagraphStyle("Body", parent=styles["BodyText"],
                           fontSize=9, leading=13, spaceAfter=4)
    mono = ParagraphStyle("Mono", parent=styles["Code"],
                           fontSize=8, leading=11, backColor=colors.HexColor("#f5f5f5"),
                           borderPadding=(4, 6, 4, 6), spaceAfter=6)
    meta = ParagraphStyle("Meta", parent=styles["Normal"],
                           fontSize=9, textColor=colors.grey)

    ACCENT = colors.HexColor("#0f3460")
    LIGHT   = colors.HexColor("#e8f4f8")
    HEADER_BG = colors.HexColor("#16213e")

    story = []

    # ── Cover ──
    story.append(Spacer(1, 0.4 * inch))
    story.append(Paragraph("LLM Benchmark Report", title_style))
    story.append(Paragraph(f"Generated: {ts}", meta))
    story.append(Paragraph(f"Models: {', '.join(seen_models.values())}", meta))
    story.append(Spacer(1, 0.15 * inch))
    story.append(HRFlowable(width="100%", thickness=2, color=ACCENT))
    story.append(Spacer(1, 0.2 * inch))

    # ── Performance summary table ──
    story.append(Paragraph("Performance Summary", h1))

    model_labels = list(seen_models.values())
    header_row = ["Task"] + [f"{lbl}\nlatency / tok·s⁻¹" for lbl in model_labels]
    table_data = [header_row]

    for task_id, rs in by_task.items():
        by_model = {r["model_id"]: r for r in rs}
        row = [rs[0]["task_label"]]
        for mid in seen_models:
            r = by_model.get(mid)
            if r and not r.get("error"):
                v = r["metadata"].get("verdict", "~")
                flag = {"pass": "✓", "fail": "✗", "manual": "~", "error": "✗"}.get(v, "~")
                row.append(f"{r['latency_s']}s {flag}\n{r['tok_per_sec']} tok/s")
            else:
                row.append("error")
        table_data.append(row)

    col_w = [2.5 * inch] + [2.5 * inch] * len(model_labels)
    tbl = Table(table_data, colWidths=col_w, repeatRows=1)
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_BG),
        ("TEXTCOLOR",  (0, 0), (-1, 0), colors.white),
        ("FONTNAME",   (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE",   (0, 0), (-1, 0), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("GRID",       (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
        ("VALIGN",     (0, 0), (-1, -1), "MIDDLE"),
        ("FONTSIZE",   (0, 1), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(tbl)
    story.append(Spacer(1, 0.25 * inch))

    # ── Aggregate stats table ──
    story.append(Paragraph("Aggregate Statistics", h1))
    agg_header = ["Model", "Avg Latency (s)", "Avg Tok/s", "Tasks", "Errors"]
    agg_data = [agg_header]
    for mid, mlabel in seen_models.items():
        model_rs = [r for r in results if r["model_id"] == mid and not r.get("error")]
        errs = sum(1 for r in results if r["model_id"] == mid and r.get("error"))
        if model_rs:
            avg_lat = round(sum(r["latency_s"] for r in model_rs) / len(model_rs), 2)
            avg_tps = round(sum(r["tok_per_sec"] for r in model_rs) / len(model_rs), 1)
            agg_data.append([mlabel, str(avg_lat), str(avg_tps), str(len(model_rs)), str(errs)])
        else:
            agg_data.append([mlabel, "—", "—", "0", str(errs)])

    agg_tbl = Table(agg_data, colWidths=[3.2*inch, 1.2*inch, 1.0*inch, 0.8*inch, 0.8*inch], repeatRows=1)
    agg_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_BG),
        ("TEXTCOLOR",  (0, 0), (-1, 0), colors.white),
        ("FONTNAME",   (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE",   (0, 0), (-1, 0), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
        ("GRID",       (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
        ("FONTSIZE",   (0, 1), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(agg_tbl)

    # ── Detailed responses ──
    story.append(PageBreak())
    story.append(Paragraph("Detailed Responses", h1))

    for task_id, rs in by_task.items():
        story.append(Paragraph(rs[0]["task_label"], h2))
        story.append(Paragraph(f"<i>Prompt: {rs[0]['prompt'][:200]}</i>", body))
        story.append(Spacer(1, 0.08 * inch))

        for r in rs:
            v = r["metadata"].get("verdict", "manual")
            badge = {"pass": "✅ PASS", "fail": "❌ FAIL", "manual": "🔍 Manual", "error": "💥 Error"}.get(v, "")
            story.append(Paragraph(
                f"<b>{r['model_label']}</b>  ·  {r['latency_s']}s  ·  {r['tokens_out']} tokens  ·  {badge}",
                body,
            ))
            if r.get("error"):
                story.append(Paragraph(f"Error: {r['error']}", body))
            else:
                # Truncate very long responses for PDF
                resp = r["response"][:800] + ("…" if len(r["response"]) > 800 else "")
                # Escape XML special chars
                resp = resp.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                story.append(Paragraph(resp, mono))
            story.append(Spacer(1, 0.06 * inch))

        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cccccc")))
        story.append(Spacer(1, 0.1 * inch))

    def draw_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.grey)
        canvas.drawCentredString(A4[0] / 2, 0.4 * inch, f"agy-benchmark · Sai Kesava Matham · {ts}  ·  Page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(
        out_path,
        pagesize=A4,
        title="LLM Benchmark Report",
        author="agy-benchmark",
        leftMargin=1.8 * cm,
        rightMargin=1.8 * cm,
        topMargin=1.8 * cm,
        bottomMargin=1.8 * cm,
    )
    doc.build(story, onFirstPage=draw_page, onLaterPages=draw_page)
    print(f"PDF saved       → {out_path}")


# ── Main ───────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate MD + PDF report from benchmark JSON")
    parser.add_argument("results_json", help="Path to results JSON file")
    parser.add_argument("--out-dir", default=None, help="Output directory (default: reports/)")
    args = parser.parse_args()

    with open(args.results_json) as f:
        payload = json.load(f)

    out_dir = args.out_dir or os.path.join(ROOT, "reports")
    os.makedirs(out_dir, exist_ok=True)

    stem = os.path.splitext(os.path.basename(args.results_json))[0]

    md_path  = os.path.join(out_dir, f"{stem}.md")
    pdf_path = os.path.join(out_dir, f"{stem}.pdf")

    md = render_markdown(payload)
    with open(md_path, "w") as f:
        f.write(md)
    print(f"Markdown saved  → {md_path}")

    render_pdf(payload, pdf_path)


if __name__ == "__main__":
    main()
